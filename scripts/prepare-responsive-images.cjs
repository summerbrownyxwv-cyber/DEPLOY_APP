// Run with sharp available on NODE_PATH. Original files are never modified.
const sharp=require('sharp');
const fs=require('node:fs/promises');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
(async()=>{
 const dest=path.join(root,'assets/responsive');await fs.mkdir(dest,{recursive:true});
 const sources=[];
 // Build display-sized variants from the WebP masters; never recompress masters.
 const collectJpeg=async folder=>{
  for(const entry of await fs.readdir(path.join(root,folder),{withFileTypes:true})){
   const file=folder+'/'+entry.name;
   if(entry.isDirectory()&&file!=='assets/responsive')await collectJpeg(file);
   else if(/\.webp$/i.test(entry.name))sources.push(file);
  }
 };
 await collectJpeg('assets');
 const manifest={};let originalBytes=0,largestBytes=0,totalBytes=0;
 for(const source of sources){
  const file=path.join(root,source),stat=await fs.stat(file);
  const name=path.basename(source,path.extname(source)),folder=path.basename(path.dirname(source)).replaceAll(' ','-');
  const meta=await sharp(file).metadata(),widths=[...new Set([768,1440,2560].map(w=>Math.min(w,meta.width)))];
  const variants=[];
  for(const width of widths){
   const output=folder+'-'+name+'-'+width+'.webp';
   const info=await sharp(file).resize({width,withoutEnlargement:true}).webp({quality:94,effort:6,lossless:/logo|horizontal|frame|ai-blue|03-01/i.test(name)}).toFile(path.join(dest,output));
   variants.push(['../../assets/responsive/'+output,info.width]);totalBytes+=info.size;
   if(width===widths.at(-1))largestBytes+=info.size;
  }
  manifest['../../'+source]={width:meta.width,height:meta.height,variants};
  originalBytes+=stat.size;
 }
 await fs.writeFile(path.join(root,'website-code/prototype/responsive-images.js'),'/* Generated by scripts/prepare-responsive-images.cjs. */\nwindow.XunAiImages='+JSON.stringify(manifest)+';\n');
 console.log(JSON.stringify({images:Object.keys(manifest).length,originalBytes,largestBytes,totalBytes}));
})().catch(error=>{console.error(error);process.exitCode=1});
